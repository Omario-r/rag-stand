def section(title):
    """Заголовок раздела. Тоже без номера — Word нумерует сам."""
    p = doc.add_paragraph(title, style="List Number")
    p.runs[0].bold = True
    return p


def clause(text):
    """Пункт второго уровня. Номера в тексте НЕТ — он в numbering.xml."""
    return doc.add_paragraph(text, style="List Number 2")


