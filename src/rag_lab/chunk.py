"""Разбор договора на дерево пунктов и нарезка на чанки.

Этап 3 роадмапа. Разбор решений — RAG/02-chunking.md.

Правило, вокруг которого всё построено: **чанк = смысловая единица документа
(пункт/подпункт), а не N символов**. Резка по символам ломает пункт посередине,
теряет иерархию и уводит номер в соседний чанк — все три дефекта не лечатся
ни моделью получше, ни реранкером.

Три вещи, которые этот модуль обязан делать правильно:

1. НОМЕР ПУНКТА — это адрес ответа. Юристу нужен «п. 4.2», а не «где-то
   в договоре». Если парсер потерял номер, чанк бесполезен, даже если текст
   в нём верный.

2. ЛИМИТ ДЛИНЫ СЧИТАЕТСЯ В ТОКЕНАХ, а не в символах. Замер 08.08.2026:
   переводной коэффициент непостоянен — 5,2 симв./токен на гладкой
   юридической прозе против 3,4 на тексте с номерами и датами. Настройка
   «2180 символов» проходит на кодексе и выходит за 512 токенов на всех
   наших договорах. Отсюда `count_tokens` — параметр, а не константа.

3. ТАБЛИЦА ОСТАЁТСЯ ПРИ СВОЁМ ПУНКТЕ. В AR-203 таблица стоит между 3.1 и 3.2
   и разрывает раздел; строка «Москва — Казань | 45 000» отдельным чанком
   не значит ничего.

Адресацию задаёт не этот модуль, а `corpus/golden-set.yaml`: он определяет,
что считается верным ответом, поэтому идентификатор чанка обязан совпадать
с его ссылками, иначе recall не посчитать. Оттуда три правила:

  * идентификатор — `<doc_id>#<номер пункта>`, голый номер. При сквозной
    нумерации (EKS-77) статья в идентификатор НЕ входит: в наборе `EKS-77#13`,
    а не «Статья 3, п. 13». Статья живёт в payload и годится для показа;
  * у SH-45 номера в тексте отсутствуют, адрес позиционный —
    `<раздел>.<порядковый номер пункта в разделе>`. Номера из стилей Word
    не восстанавливаем: они плоские, и восстановленный номер разошёлся бы
    с тем, что Word показывает юристу. Неверная ссылка хуже отсутствующей;
  * пункты допсоглашения — отдельные чанки со своими адресами. Исходный
    пункт не переписывается и не удаляется, он помечается `superseded`.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

# Предел эмбеддера в токенах. У multilingual-e5-large — 512, у Qwen3 больше,
# но целимся в меньший: конфигурация партнёра должна проходить тоже.
MAX_TOKENS = 512

# Целевого и минимального размера чанка здесь нет намеренно. Стояли
# TARGET_TOKENS = 350 и MIN_TOKENS = 40, но ни одна строка модуля их не
# читала: чанк задаётся структурой документа (пункт и его подпункты),
# а не желаемой длиной. Константа, которую никто не спрашивает, читается
# как действующая настройка и врёт. Появится подбор размера на этапе 8 —
# появятся и они, вместе с кодом, который ими пользуется.

# Консервативная оценка, когда токенизатора под рукой нет.
#
# Замер 09.08.2026 на всех 144 чанках корпуса, `scripts/measure-tokens.py`.
# Мерился текст, который реально уходит в вектор (с шапкой-адресом), а не
# голый пункт:
#
#   токенизатор              симв./токен: мин   мед   max
#   multilingual-e5-large              2,33  3,26  4,03
#   Qwen3-Embedding-0.6B               1,46  1,99  2,51
#
# Два вывода, оба против прежнего значения 3,4:
#
#   1. Токенизаторы несопоставимы. Qwen3 дробит русский текст вдвое мельче
#      e5 — один и тот же чанк это 124 токена против 76 по медиане. Число
#      «символов на токен» без имени модели не значит ничего.
#   2. Прежние 3,4 взяты из замера на окнах по 2180 символов, где плотность
#      усредняется по длинному куску. На коротких чанках с таблицами
#      и номерами плотность доходит до 2,33 у e5 и 1,46 у Qwen3, то есть
#      оценка занижала — в ту сторону, в которую консервативной оценке
#      ошибаться нельзя.
#
# Берём 1,4 — ниже худшей наблюдавшейся плотности у более мелкого из двух
# токенизаторов. Оценка станет завышать (для e5 вдвое), и это правильная
# сторона: лишний раз разрезать чанк дешевле, чем молча отдать модели текст
# длиннее предела. На корпусе первой партии лишних разрезов не даёт ни одного.
CHARS_PER_TOKEN_WORST = 1.4


def estimate_tokens(text: str) -> int:
    """Оценка числа токенов по символам — заведомо с запасом.

    Нужна, чтобы разбор договора не требовал поднятого llama.cpp. Когда сервер
    есть, вместо этой функции передаётся точный счётчик: см. `tokens_via_server`.
    """
    return int(len(text) / CHARS_PER_TOKEN_WORST) + 1


def tokens_via_server(embedder) -> "callable":
    """Точный счётчик токенов через /tokenize работающего llama.cpp.

    Возвращает функцию, а не число: подставляется в `chunk_document`
    вместо `estimate_tokens`, когда стенд поднят.
    """

    def count(text: str) -> int:
        return len(embedder._post("/tokenize", {"content": text})["tokens"])

    return count


# --- распознавание структуры ---

# Заголовок раздела: "## 4. ОТВЕТСТВЕННОСТЬ СТОРОН" или "## Статья 3. Название"
RE_SECTION = re.compile(r"^#{1,6}\s+(?:(Статья|Раздел)\s+)?(\d+)\.?\s*(.*)$")
# Заголовок приложения: "# Приложение № 1 к Договору ..." — начинает новую
# часть документа. Приложение живёт под тем же doc_id: юрист ищет
# «по договору», а не «по файлу» (RAG/02-chunking.md).
RE_APPENDIX = re.compile(r"^#{1,6}\s+Приложение\s*№?\s*(\d+)")
# Заголовок документа: единственная "# ..." в начале файла
RE_TITLE = re.compile(r"^#\s+(?!\d)(.+)$")
# Номер пункта в начале абзаца: "4.2." / "3.4.3.1." / "17." — точка в конце
# необязательна, но точки внутри обязаны разделять только цифры.
RE_CLAUSE = re.compile(r"^(\d+(?:\.\d+)*)\.?\s+(?=[«А-ЯЁA-Z])")
# Пункт приложения: "П.1." — своя нумерация, не пересекается с договором
RE_CLAUSE_APP = re.compile(r"^П\.(\d+)\.?\s+(?=[«А-ЯЁA-Z])")
# Строка таблицы Markdown
RE_TABLE = re.compile(r"^\s*\|")
# Горизонтальная линейка markdown. Отделяет приложение от договора и потому
# попадает в буфер последнего пункта раздела: в EKS-77 пункт 33 уезжал
# в индекс со строкой "---" на конце. Разделитель таблицы "|---|" под это
# правило не подходит — он начинается с вертикальной черты.
RE_HRULE = re.compile(r"^\s*(?:-{3,}|\*{3,}|_{3,})\s*$")
# Разделы, которые не идут в векторный индекс: реквизиты и подписи шумят
# и тянут на себя похожие запросы, их место — SQL (RAG/02-chunking.md)
RE_NOT_INDEXED = re.compile(r"реквизит|подписи\s+сторон", re.I)


@dataclass
class Clause:
    """Пункт договора — узел дерева."""

    number: str  # "4.2" или "13" при сквозной нумерации; "" если номера нет
    text: str  # чистый текст пункта, без служебной шапки
    section_no: str = ""  # номер раздела/статьи, в котором лежит пункт
    section_title: str = ""
    level: int = 1  # глубина: 4.2 -> 2, 3.4.3.1 -> 4
    parent: str = ""  # number родителя, "" у верхнего уровня
    has_table: bool = False
    children: list[str] = field(default_factory=list)
    part: str = "договор"  # "договор" или "приложение N"
    indexed: bool = True  # False у реквизитов и подписей
    # Сквозная нумерация: пункты идут 1…33, а разделы называются «Статья N»,
    # и номер пункта с номером статьи никак не связан (EKS-77). Свойство
    # документа, а не пункта: проставляется парсером сразу всем пунктам.
    # Считать его по одному пункту нельзя — у первого пункта первой статьи
    # номер совпадает с номером статьи, и он один выглядел бы иерархическим
    # (EKS-77#1 показывался как «п. 1», а весь остальной документ —
    # как «Статья N, п. M»).
    sequential: bool = False


def parse(path: str | Path) -> tuple[str, list[Clause]]:
    """Файл договора -> (заголовок документа, плоский список пунктов).

    Дерево задаётся полями `parent`/`children`, а не вложенностью: так проще
    и сериализовать в payload, и обходить.
    """
    path = Path(path)
    if path.suffix == ".docx":
        return parse_docx(path)
    return parse_markdown(path)


# Стили, которыми размечен SH-45. Word показывает номера, потому что стиль
# несёт numPr; в извлечённом тексте номеров нет ни одного.
DOCX_SECTION_STYLE = "List Number"
DOCX_CLAUSE_STYLE = "List Number 2"


def parse_docx(path: str | Path) -> tuple[str, list[Clause]]:
    """Разбор .docx с автонумерацией Word — номера восстанавливаются позиционно.

    Главная ловушка корпуса. В `SH-45` нумерация задана стилями (`numPr`,
    numId 5 и 6), поэтому Word номера рисует, а `python-docx` возвращает
    31 пункт, из которых ни один не начинается с цифры.

    Номера из стилей НЕ восстанавливаем, хотя технически могли бы: в файле
    они плоские — две независимые последовательности на два уровня, а не
    иерархические `4.2`. Восстановленный номер разошёлся бы с тем, что Word
    показывает юристу на экране, а неверная ссылка хуже отсутствующей.

    Вместо этого адрес позиционный, ровно как задано в `corpus/golden-set.yaml`:
    `<порядковый номер раздела>.<порядковый номер пункта в разделе>`.

    Реквизиты и подписи (стиль Normal после последнего раздела) в пункты
    не попадают: они шумят и тянут на себя похожие запросы, их место — SQL
    (RAG/02-chunking.md).
    """
    from docx import Document  # локально: markdown-ветка не должна тянуть зависимость

    doc = Document(str(path))
    doc_title = ""
    section_no = 0
    clause_no = 0
    section_title = ""
    clauses: list[Clause] = []

    for par in doc.paragraphs:
        text = par.text.strip()
        if not text:
            continue
        style = par.style.name

        if style == DOCX_SECTION_STYLE:
            section_no += 1
            clause_no = 0
            section_title = text
            continue

        if style == DOCX_CLAUSE_STYLE:
            if section_no == 0:
                # пункт до первого раздела — структура файла не та, что ожидали
                raise ValueError(f"{path}: пункт до первого раздела: {text[:60]!r}")
            clause_no += 1
            clauses.append(
                Clause(
                    number=f"{section_no}.{clause_no}",
                    text=text,
                    section_no=str(section_no),
                    section_title=section_title,
                    level=2,
                    parent="",  # родитель — раздел, а не пункт
                )
            )
            continue

        # Normal: заголовок документа — первый непустой; остальное (место,
        # дата, преамбула, реквизиты) в пункты не идёт
        if not doc_title:
            doc_title = text

    return doc_title, clauses


def parse_markdown(path: str | Path) -> tuple[str, list[Clause]]:
    """Разбор договора в markdown: номера пунктов есть прямо в тексте."""
    lines = Path(path).read_text(encoding="utf-8").splitlines()

    doc_title = ""
    section_no = section_title = ""
    clauses: list[Clause] = []
    current: Clause | None = None
    buf: list[str] = []

    def flush():
        nonlocal current, buf
        if current is not None:
            current.text = "\n".join(buf).strip()
            clauses.append(current)
        current, buf = None, []

    part = "договор"

    for line in lines:
        if m := RE_APPENDIX.match(line):
            flush()
            part = f"приложение {m.group(1)}"
            section_no, section_title = "", ""
            continue

        if not doc_title and (m := RE_TITLE.match(line)):
            doc_title = m.group(1).strip()
            continue

        if m := RE_SECTION.match(line):
            flush()
            section_no, section_title = m.group(2), m.group(3).strip()
            continue

        if m := (RE_CLAUSE_APP.match(line) if part != "договор" else RE_CLAUSE.match(line)):
            flush()
            number = f"П.{m.group(1)}" if part != "договор" else m.group(1)
            current = Clause(
                number=number,
                text="",
                section_no=section_no,
                section_title=section_title,
                level=number.count(".") + 1 if part == "договор" else 1,
                parent=number.rsplit(".", 1)[0] if "." in number and part == "договор" else "",
                part=part,
                # реквизиты встречаются в двух видах: отдельным разделом
                # (TR-114 «## 10. АДРЕСА И РЕКВИЗИТЫ СТОРОН») и пунктом внутри
                # заключительных положений (AR-203 «7.3. Реквизиты Сторон:»)
                indexed=not (RE_NOT_INDEXED.search(section_title or "")
                             or RE_NOT_INDEXED.search(line)),
            )
            buf = [line.strip()]
            continue

        if current is not None:
            if RE_HRULE.match(line):
                continue
            if RE_TABLE.match(line):
                current.has_table = True
            buf.append(line)

    flush()

    # Сквозная нумерация — свойство всего документа (см. поле Clause.sequential)
    sequential = any(
        c.level == 1 and c.section_no and c.number != c.section_no
        for c in clauses
        if c.part == "договор"
    )
    for c in clauses:
        c.sequential = sequential and c.part == "договор"

    # связать детей с родителями
    by_number = {c.number: c for c in clauses}
    for c in clauses:
        if c.parent and c.parent in by_number:
            by_number[c.parent].children.append(c.number)
        elif c.parent:
            # родителя нет в файле: "3.2.5" без "3.2" — не ошибка парсера,
            # так бывает в допсоглашениях, которые дополняют чужой документ
            c.parent = ""

    return doc_title, clauses


def chunk_id(doc_id: str, c: Clause) -> str:
    """Идентификатор чанка — ровно та форма, что в golden-set.yaml.

    Менять её нельзя в одностороннем порядке: по этой строке считается
    совпадение с золотым набором, то есть весь recall. Если форма меняется,
    она меняется одновременно здесь и в наборе.
    """
    return f"{doc_id}#{c.number}"


def display(doc_id: str, c: Clause) -> str:
    """Как адрес показывается человеку — отдельно от идентификатора.

    Здесь статью при сквозной нумерации добавить можно и полезно: юристу
    «Статья 3, п. 13» говорит больше, чем «п. 13». На метрику не влияет,
    потому что сравнение идёт по `chunk_id`.
    """
    if not c.number:
        return f"{doc_id}, без номера"
    if c.sequential and c.section_no:
        return f"{doc_id}, Статья {c.section_no}, п. {c.number}"
    return f"{doc_id}, п. {c.number}"


# Допсоглашение делает с договором три РАЗНЫЕ вещи, и путать их нельзя:
# изложить в новой редакции (старый пункт больше не действует), исключить
# (пункта больше нет), дополнить новым пунктом (старого не было вовсе —
# ничего не отменяется). Для поиска все три меняют «что действует сейчас»,
# но для извлечения реквизитов (RAG/07-extraction.md) разница существенна:
# «исключён» и «изменён» дают разные значения в истории поля.
RE_AMENDS = re.compile(r"Пункт\s+(\d+(?:\.\d+)*)\s+Договора\s+изложить")
RE_EXCLUDES = re.compile(r"Пункт\s+(\d+(?:\.\d+)*)\s+Договора\s+исключить")
RE_ADDS = re.compile(r"Дополнить\s+Договор\s+пунктом\s+(\d+(?:\.\d+)*)")


def amendment(c: Clause) -> tuple[str, str]:
    """Что этот пункт допсоглашения делает с основным договором.

    Возвращает (операция, номер пункта): "изменяет" | "исключает" | "добавляет",
    либо ("", "") — если пункт ничего не меняет.

    Допсоглашение НЕ применяется к договору и не переписывает его: пункты ДС
    остаются отдельными чанками со своими адресами, а исходный пункт получает
    пометку. Так задано золотым набором — в нём `relevant` и `superseded`
    разные поля, и в вопросе «какая СЕЙЧАС предельная сумма» верен только
    пункт ДС, а исходный числится отдельно. Применённая правка стёрла бы
    возможность показать первоначальную редакцию, а для юриста это и есть
    предмет спора.
    """
    for op, rx in (("изменяет", RE_AMENDS), ("исключает", RE_EXCLUDES), ("добавляет", RE_ADDS)):
        if m := rx.search(c.text):
            return op, m.group(1)
    return "", ""


@dataclass
class Chunk:
    """Единица индекса: один пункт или родитель со своими подпунктами."""

    id: str  # <doc_id>#<номер ведущего пункта> — совпадает с golden-set
    clause_ids: list[str]  # все пункты, вошедшие в чанк
    text: str  # чистый текст, идёт в контекст модели и в цитаты
    embed_text: str  # с шапкой-адресом, идёт в вектор
    payload: dict


def chunk_document(
    doc_id: str,
    doc_title: str,
    clauses: list[Clause],
    doc_type: str = "",
    count_tokens=estimate_tokens,
) -> list[Chunk]:
    """Пункты -> чанки. Родитель склеивается со своими подпунктами.

    Правило склейки выбрано по замеру корпуса 08.08.2026, а не по умолчанию:
    медиана пункта — 39 токенов, 53 % короче 40. При этом самые короткие
    пункты почти все оказались РОДИТЕЛЯМИ перечислений — «3.1. Перевозчик
    обязан:» на 7 токенов, а следом 3.1.1…3.1.5. Склейка «с соседями до N
    токенов», как написано в RAG/02-chunking.md, разрезала бы такое
    перечисление посередине; склейка «родитель + его дети» сохраняет и смысл,
    и адрес.

    Идентификатор чанка — адрес ведущего пункта, поэтому совпадение
    с золотым набором считается по `clause_ids`, а не по `id`: вопрос может
    указывать на подпункт, попавший внутрь чанка родителя.
    """
    by_number = {c.number: c for c in clauses}
    consumed: set[str] = set()
    chunks: list[Chunk] = []

    def descendants(c: Clause) -> list[Clause]:
        out = []
        for n in c.children:
            child = by_number[n]
            out.append(child)
            out.extend(descendants(child))
        return out

    for c in clauses:
        if not c.indexed or c.number in consumed:
            continue

        group = [c] + [d for d in descendants(c) if d.indexed]
        consumed.update(g.number for g in group)

        # Слишком длинная группа режется вторично: родитель повторяется
        # в каждой части как контекст, иначе «4.1.4» без «Перевозчик обязан:»
        # теряет смысл. На корпусе первой партии не срабатывает ни разу —
        # самый длинный чанк 400 токенов при пределе 512, — то есть эта
        # ветка ПОКА НЕ ПРОВЕРЕНА на реальных данных.
        parts, cur = [], [group[0]]
        for g in group[1:]:
            probe = cur + [g]
            if len(cur) > 1 and count_tokens("\n".join(x.text for x in probe)) > MAX_TOKENS:
                parts.append(cur)
                cur = [group[0], g]
            else:
                cur = probe
        parts.append(cur)

        for i, part in enumerate(parts):
            # Первая часть адресуется родителем: её текст с него и начинается,
            # и юристу нужен адрес «п. 3.1», а не «п. 3.1.1». Продолжения
            # адресуются своим подпунктом — родитель в них только повторённый
            # контекст.
            lead = part[0] if (i == 0 or len(part) == 1) else part[1]
            ids = [g.number for g in part]
            text = "\n".join(g.text for g in part)
            addr = display(doc_id, lead)
            chunks.append(
                Chunk(
                    id=f"{doc_id}#{lead.number}",
                    clause_ids=ids,
                    text=text,
                    embed_text=contextualize(doc_title, lead, addr, text),
                    payload={
                        "doc_id": doc_id,
                        "doc_type": doc_type,
                        "part": lead.part,
                        "section_no": lead.section_no,
                        "section_title": lead.section_title,
                        "clause_no": lead.number,
                        "clause_ids": ids,
                        "parent_id": f"{doc_id}#{lead.parent}" if lead.parent else "",
                        "has_table": any(g.has_table for g in part),
                        # [{"операция": "изменяет", "пункт": "4.2"}, ...]
                        "amends": [
                            {"операция": op, "пункт": num}
                            for g in part
                            if (op := amendment(g)[0]) and (num := amendment(g)[1])
                        ],
                        "text": text,
                    },
                )
            )

    return chunks


def contextualize(doc_title: str, c: Clause, addr: str, text: str) -> str:
    """Текст, который пойдёт в вектор: адрес + раздел + текст всей группы.

    Дёшево, а качество поиска растёт заметно — вектор «знает», что речь
    о неустойке в договоре перевозки, даже если слова «перевозка» в пункте
    нет (RAG/02-chunking.md). Чистый текст пункта хранится отдельно:
    он идёт в контекст модели и в цитаты, там шапка не нужна.

    `text` передаётся отдельно и намеренно: у склеенного чанка шапка строится
    по ведущему пункту, а текст — по всей группе. Первая редакция дописывала
    шапку к `c.text`, а потом отрезала последний абзац и подставляла групповой
    текст. На пунктах с пустой строкой внутри — таблицы, цитаты допсоглашения —
    отрезался не тот абзац, и текст пункта уходил в вектор дважды (12 чанков
    из 144).
    """
    head = doc_title
    if c.section_no:
        head += f"\nРаздел {c.section_no}. {c.section_title} → {addr}"
    elif c.part != "договор":
        # приложение: своего раздела у него нет, но без адреса вектор не знает,
        # что таблица тарифов относится именно к этому договору
        head += f"\n{c.part.capitalize()} → {addr}"
    else:
        head += f"\n{addr}"
    return f"{head}\n\n{text}"
