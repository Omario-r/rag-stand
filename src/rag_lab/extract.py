"""Извлечение реквизитов: схема полей, проверка цитат, нормализация. Этап 7.

Разбор — RAG/07-extraction.md, лаба — RAG/lab-07-extraction.md.

ГЛАВНОЕ ОТЛИЧИЕ ОТ ПОИСКА, из которого следует всё остальное. Плохой поиск
виден сразу — «ничего не нашлось». Плохое извлечение невидимо: модель,
не найдя суммы, выдаёт правдоподобное число в правильном формате, оно
ложится в SQL, и через месяц юрист получает достоверно выглядящий ответ
«договоров свыше 5 млн — четыре», который просто неверен.

Отсюда всё устройство этого модуля:

  * значение приходит ТОЛЬКО с цитатой, и цитата механически проверяется
    на вхождение в документ. Модель может выдумать число, но не может
    выдумать цитату, которая пройдёт проверку подстроки;
  * `None` — легальный и поощряемый ответ. Пустое поле честнее выдуманного;
  * нормализация — отдельный шаг, КОДОМ. Модель возвращает то, что написано
    в документе; приведение к типам делает код, без модели. Не смешивать
    «понять» и «привести к формату».

Модуль намеренно не содержит вызова модели: он про то, что делается
до и после неё.
"""

