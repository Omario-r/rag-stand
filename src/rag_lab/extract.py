def json_schema(fields: dict[str, str]) -> dict:
    """JSON Schema для `response_format` llama.cpp.

    Каждое поле — объект со значением, цитатой и номером пункта, а не голое
    значение: без цитаты записывать в SQL нечего.

    ЛОВУШКА, о которую спотыкаются все: схема ограничивает вывод, но
    В ПРОМПТ НЕ ПОДСТАВЛЯЕТСЯ. Модель «не видит» схему — она просто не может
    выйти за её рамки. Без словесного описания полей получится валидный JSON,
    заполненный чем попало. Поэтому рядом есть `prompt_for`.
    """
    prop = {
        "type": ["object", "null"],
        "properties": {
            "value": {"type": ["string", "number", "boolean", "null"]},
            "quote": {"type": "string"},
            "clause": {"type": ["string", "null"]},
        },
        "required": ["value", "quote"],
        "additionalProperties": False,
    }
    return {
        "type": "object",
        "properties": {name: dict(prop) for name in fields},
        "required": list(fields),
        "additionalProperties": False,
    }


def prompt_for(fields: dict[str, str], text: str) -> str:
    """Промпт с описанием полей. Схема их не описывает — описываем словами."""
    lines = "\n".join(f"- {name}: {descr}" for name, descr in fields.items())
    return (
        "Ниже фрагменты договора. Заполни поля строго по тексту.\n\n"
        f"Поля:\n{lines}\n\n"
        "Правила:\n"
        "- если поля в тексте нет — верни null, НЕ выводи из общих соображений;\n"
        "- quote — дословная цитата из текста, подтверждающая значение;\n"
        "- clause — номер пункта, откуда взята цитата;\n"
        "- значения не нормализуй: пиши как в документе.\n\n"
        f"Текст:\n{text}"
    )


# --- Проверка цитаты -------------------------------------------------------

_WS = re.compile(r"\s+")


def normalize_for_match(s: str) -> str:
    """Приведение к виду, в котором сравниваются цитата и документ.

    Убираются различия, о которых модель знать не обязана: неразрывные
    пробелы, разные виды кавычек и тире, регистр, переносы строк.
    НЕ убираются цифры и слова — иначе проверка перестанет проверять.
    """
    s = unicodedata.normalize("NFKC", s)
    for a, b in (("«", '"'), ("»", '"'), ("“", '"'), ("”", '"'), ("„", '"'),
                 ("—", "-"), ("–", "-"), (" ", " "), ("ё", "е")):
        s = s.replace(a, b)
    return _WS.sub(" ", s).strip().lower()


def quote_ok(document: str, quote: str) -> bool:
    """Цитата обязана быть точной подстрокой документа.

    Не совпало — значение НЕ записывается в SQL, поле уходит в очередь
    на проверку человеком. Это единственный механический барьер против
    тихой галлюцинации, и ослаблять его нечёткими сравнениями нельзя:
    «похожая» цитата — это уже не цитата.
    """
    if not quote or not quote.strip():
        return False
    return normalize_for_match(quote) in normalize_for_match(document)


# --- Нормализация: даты ----------------------------------------------------

MONTHS = {
    "января": 1, "февраля": 2, "марта": 3, "апреля": 4, "мая": 5, "июня": 6,
    "июля": 7, "августа": 8, "сентября": 9, "октября": 10, "ноября": 11, "декабря": 12,
}

RE_DATE_RU = re.compile(r"[«\"]?(\d{1,2})[»\"]?\s+([а-яё]+)\s+(\d{4})", re.I)
RE_DATE_NUM = re.compile(r"\b(\d{1,2})[.\-/](\d{1,2})[.\-/](\d{4})\b")


def parse_date_ru(s: str) -> str | None:
    """«12» марта 2026 г. -> 2026-03-12. Возвращает None, если не разобрал.

    None здесь — не отказ, а честный ответ: неразобранная дата уходит
    в очередь, а не записывается наугад.
    """
    if not s:
        return None
    if m := RE_DATE_RU.search(s):
        day, month_word, year = m.groups()
        month = MONTHS.get(month_word.lower())
        if month:
            return f"{year}-{month:02d}-{int(day):02d}"
    if m := RE_DATE_NUM.search(s):
        day, month, year = (int(x) for x in m.groups())
        if 1 <= month <= 12 and 1 <= day <= 31:
            return f"{year}-{month:02d}-{day:02d}"
    return None


# --- Нормализация: суммы ---------------------------------------------------

# Числительные во ВСЕХ падежах, а не только в именительном. В договорах
# пропись почти всегда склоняется: «в размере 1 500 (одной тысячи пятисот)
# рублей». Словарь из одних именительных форм разбирал эту строку как 1 000
# и объявлял расхождение с цифрами там, где расхождения нет, — то есть слал
# в очередь к человеку исправные договоры. Ложная тревога в такой проверке
# хуже её отсутствия: на неё перестают смотреть.
#
# Сопоставление по ПОЛНОМУ слову, а не по основе: основа «ст» для «сто»
# поймала бы «стоимость».

ONES: dict[str, int] = {}
SCALES: dict[str, int] = {}


def _forms(table: dict[str, int], value: int, *words: str) -> None:
    for w in words:
        table[w.replace("ё", "е")] = value


