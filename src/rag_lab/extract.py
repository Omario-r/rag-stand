# Числительные во ВСЕХ падежах, а не только в именительном. В договорах
# пропись почти всегда склоняется: «в размере 1 500 (одной тысячи пятисот)
# рублей». Словарь из одних именительных форм разбирал эту строку как 1 000
# и объявлял расхождение с цифрами там, где расхождения нет, — то есть слал
# в очередь к человеку исправные договоры. Ложная тревога в такой проверке
# хуже её отсутствия: на неё перестают смотреть.
#
# Сопоставление по ПОЛНОМУ слову, а не по основе: основа «ст» для «сто»
# поймала бы «стоимость».

ONES: dict[str, int] = {}
SCALES: dict[str, int] = {}


def _forms(table: dict[str, int], value: int, *words: str) -> None:
    for w in words:
        table[w.replace("ё", "е")] = value


