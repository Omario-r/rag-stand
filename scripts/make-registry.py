def _name_variants(short: str) -> list[str]:
    """Три написания одной компании — то, ради чего контрагент опознаётся по ИНН.

    Для SQL «ООО «Ромашка»», «ООО "Ромашка"» и полная форма — три разные
    компании, и вопрос «все договоры с Ромашкой» вернёт треть правды.
    """
    if short.startswith("ИП"):
        return [short, short.replace("ИП ", "Индивидуальный предприниматель ")]
    core = short.split("«")[1].rstrip("»")
    return [
        f'ООО "{core}"',
        f"ООО {core}",
        f"Общество с ограниченной ответственностью «{core}»",
    ]


def make_orgs(rnd: random.Random, n_new: int, n_ip: int) -> list[dict]:
    """Организации: партия 1 как есть, новые — сгенерированные.

    Сколько среди новых ИП — задаётся числом, а не вероятностью. У ИП ИНН
    на 12 знаков с двумя контрольными цифрами, у юрлица на 10 с одной; это
    разные ветки и в генераторе, и в проверке пайплайна. При «примерно 15 %»
    на шестнадцати организациях выпадало то одна, то три — то есть ветка
    могла остаться почти непроверенной, и заметить это было бы нечем.
    """
    orgs: list[dict] = []
    ip_idx = set(rnd.sample(range(n_new), min(n_ip, n_new)))
    for inn, short, city, roles in BATCH_1_ORGS:
        orgs.append({
            "инн": inn,
            "название_кратко": short,
            "название_полно": _name_variants(short)[-1],
            "варианты_написания": _name_variants(short)[:-1],
            "город": city,
            "роли": roles,
            "партия": 1,
            "инн_валиден": inn_valid(inn),
            "примечание": "из партии 1, не менять: на этом корпусе сделаны замеры 08–10.08.2026",
        })

    # Имена партии 1 заняты: иначе генератор выдаёт второе ООО «Ромашка»
    # с другим ИНН. Два юрлица с одним названием — вещь в жизни возможная
    # и для проверки «контрагент опознаётся по ИНН» даже полезная, но такое
    # заводится намеренно и с пометкой, а не случайно из общего словаря.
    used_cores = {o["название_кратко"].split("«")[1].rstrip("»")
                  for o in orgs if "«" in o["название_кратко"]}
    for i in range(n_new):
        city, region = rnd.choice(_CITY)
        ip = i in ip_idx

        # Подписант рисуется до организации: у ИП он и есть организация,
        # и разойтись они не должны. Первая редакция рисовала имя дважды —
        # получался «ИП Фёдоров Андрей Викторович» за подписью Беловой.
        sur = rnd.choice(_SURNAME)
        female = rnd.random() < 0.25
        first, patr = rnd.choice(_NAME_F if female else _NAME)
        if female:
            sur += "а"
        person = f"{sur} {first} {patr}"

        if ip:
            short = f"ИП {person}"
            inn = _inn12(rnd, region + "0")
            org = {"огрнип": _ogrn(rnd, region, ip=True)}
        else:
            while True:
                core = (rnd.choice(_PLAIN) if rnd.random() < 0.4
                        else rnd.choice(_PREFIX) + rnd.choice(_ROOT))
                if core not in used_cores:
                    used_cores.add(core)
                    break
            short = f"ООО «{core}»"
            inn = _inn10(rnd, region + "0")
            org = {"кпп": _kpp(inn), "огрн": _ogrn(rnd, region)}

        variants = _name_variants(short)
        org.update({
            "инн": inn,
            "название_кратко": short,
            "название_полно": variants[-1],
            "варианты_написания": variants[:-1],
            "город": city,
            "адрес": f"{city}, ул. {rnd.choice(_STREET)}, д. {rnd.randint(1, 90)}",
            "руководитель": {
                "фио": person,
                "должность": "индивидуальный предприниматель" if ip else rnd.choice(_POST),
                "действует_на_основании": "свидетельства" if ip else "Устава",
            },
            "роли": [],
            "партия": 2,
            "инн_валиден": True,
        })
        orgs.append(org)
    return orgs


def make_cases(rnd: random.Random, orgs: list[dict], n_new: int) -> list[dict]:
    """Дела: кто с кем, когда, на сколько.

    Контрагенты назначаются так, чтобы каждый встретился в 2–4 делах: иначе
    вопрос «все договоры с этим перевозчиком» проверять не на чем.
    """
    cases: list[dict] = []
    for cid, kind, number, signed, fname, ds_name in BATCH_1_CASES:
        case = {
            "дело": cid, "тип": kind, "номер": number, "дата": signed,
            "файл": fname,
            "партия": 1, "допсоглашение": bool(ds_name),
            "примечание": "из партии 1, документы уже написаны",
        }
        if ds_name:
            case["файл_допсоглашения"] = ds_name
        cases.append(case)

    pool = [o for o in orgs if o["партия"] == 2]
    counts = {o["инн"]: 0 for o in pool}
    seq = {lat: 300 for lat, _, _ in _TYPES.values()}

    for _ in range(n_new):
        kind = rnd.choice(list(_TYPES))
        lat, cyr, (role_a, role_b) = _TYPES[kind]
        seq[lat] += rnd.randint(1, 7)

        # Из наименее занятых, чтобы никто не остался с одним договором.
        ranked = sorted(pool, key=lambda o: (counts[o["инн"]], rnd.random()))
        a, b = ranked[0], ranked[1]
        counts[a["инн"]] += 1
        counts[b["инн"]] += 1
        for org, role in ((a, role_a), (b, role_b)):
            if role not in org["роли"]:
                org["роли"].append(role)

        signed = date(2025, 1, 1) + timedelta(days=rnd.randint(0, 640))
        months = rnd.choice([12, 12, 18, 24, 36])
        end = signed + timedelta(days=months * 30)
        amount = rnd.choice([1_200_000, 2_500_000, 3_800_000, 4_500_000,
                             6_200_000, 8_000_000, 12_400_000, 15_000_000])
        has_ds = rnd.random() < 0.30
        case = {
            "дело": f"{lat}-{seq[lat]}",
            "тип": kind,
            "номер": f"{cyr}-{seq[lat]}/{signed.year}",
            "файл": f"{lat}-{seq[lat]}-{signed.year}.md",
            "дата": signed.isoformat(),
            "срок_месяцев": months,
            "дата_окончания": end.isoformat(),
            "стороны": [
                {"роль": role_a, "инн": a["инн"], "название": a["название_кратко"]},
                {"роль": role_b, "инн": b["инн"], "название": b["название_кратко"]},
            ],
            "предельная_сумма": money(amount),
            "срок_оплаты_дней": rnd.choice([5, 7, 10, 14, 20, 30]),
            "неустойка_процент": rnd.choice([0.05, 0.1, 0.15, 0.2]),
            "приложение": rnd.random() < 0.40,
            "допсоглашение": has_ds,
            "партия": 2,
        }
        # Приложение — отдельный файл, а не раздел внутри договора. В партии 1
        # приложение к EKS-77 живёт внутри документа, и парсер это умеет;
        # но в жизни спецификация приходит отдельным файлом, а схема БД
        # на приложениях не проверена вовсе. Пусть корпус проверяет
        # тот случай, с которым столкнёмся, а не тот, который проще.
        if case["приложение"]:
            case["файл_приложения"] = f"{lat}-{seq[lat]}-{signed.year}-P1.md"
        if has_ds:
            case["файл_допсоглашения"] = f"{lat}-{seq[lat]}-{signed.year}-DS1.md"

        # Ставки зависят от типа договора. Простоя транспорта в аренде ТС
        # не бывает, а поле, которого в договоре нет вовсе, — самая опасная
        # категория для извлечения: модель кладёт в него значение
        # из ближайшего похожего пункта, и оба барьера молчат, потому что
        # цитата подлинная (запись 10.08.2026 в журнале решений). Пусть корпус
        # проверяет и это — то есть умеет ли модель честно промолчать.
        if kind in ("перевозка", "экспедирование"):
            case["ставка_простоя"] = money(rnd.choice([800, 1_200, 1_500, 1_800, 2_400]))
            case["бесплатное_время_часов"] = rnd.choice([2, 4, 6, 8, 12])
        elif kind == "аренда_ТС":
            case["арендная_плата_в_месяц"] = money(
                rnd.choice([90_000, 120_000, 150_000, 210_000]))
            case["обеспечительный_платёж"] = money(
                rnd.choice([100_000, 150_000, 300_000]))
        else:                                       # хранение
            case["плата_за_паллетоместо_в_сутки"] = money(rnd.choice([45, 60, 80, 110]))
            case["сверхнормативное_хранение_в_сутки"] = money(rnd.choice([120, 180, 250]))

        if has_ds:
            # Допсоглашение к истёкшему договору — бессмыслица: не раньше двух
            # месяцев после подписания и не позже, чем за месяц до окончания.
            ds_date = signed + timedelta(days=rnd.randint(60, months * 30 - 30))
            changeable = [k for k in ("предельная_сумма", "срок_оплаты_дней",
                                      "дата_окончания", "ставка_простоя",
                                      "арендная_плата_в_месяц",
                                      "плата_за_паллетоместо_в_сутки")
                          if k in case or k == "дата_окончания"]
            case["допсоглашение_детали"] = {
                "дата": ds_date.isoformat(),
                "меняет": sorted(rnd.sample(changeable,
                                            k=min(len(changeable), rnd.randint(2, 4)))),
                "новая_сумма": money(int(amount * rnd.choice([1.2, 1.4, 1.5]))),
                "новая_дата_окончания": (end + timedelta(
                    days=rnd.choice([180, 365]))).isoformat(),
            }
        cases.append(case)
    return cases


def build(seed: int, n_orgs: int, n_cases: int, n_ip: int = 4) -> dict:
    rnd = random.Random(seed)
    orgs = make_orgs(rnd, n_orgs, n_ip)
    cases = make_cases(rnd, orgs, n_cases)
    return {
        "мета": {
            "создан": date.today().isoformat(),
            "seed": seed,
            "чем": "scripts/make-registry.py",
            "зачем": (
                "Общие для всей партии 2 реквизиты: ИНН с верной контрольной "
                "суммой, повторяющиеся контрагенты, суммы с прописью. "
                "Авторы документов берут значения отсюда и не придумывают свои."
            ),
            "организаций": len(orgs),
            "из_них_ИП": sum(1 for o in orgs if o["название_кратко"].startswith("ИП")),
            "дел": len(cases),
            "из_партии_1": sum(1 for c in cases if c["партия"] == 1),
        },
        "организации": orgs,
        "дела": cases,
    }


def check(data: dict) -> list[str]:
    """Пересчитать всё, что можно пересчитать, и сверить с записанным."""
    bad: list[str] = []
    seen_inn: set[str] = set()

    for o in data["организации"]:
        inn = o["инн"]
        if inn in seen_inn:
            bad.append(f"ИНН {inn} встречается дважды")
        seen_inn.add(inn)
        if inn_valid(inn) != o["инн_валиден"]:
            bad.append(f"{inn}: пометка «инн_валиден» разошлась с контрольной суммой")
        if o["партия"] == 2 and not inn_valid(inn):
            bad.append(f"{inn}: партия 2, а контрольная сумма не сходится")
        for key in ("огрн", "огрнип"):
            if key in o and not ogrn_valid(o[key]):
                bad.append(f"{inn}: {key} {o[key]} не проходит контрольную сумму")

    known = {o["инн"] for o in data["организации"]}
    seen_case: set[str] = set()
    for c in data["дела"]:
        if c["дело"] in seen_case:
            bad.append(f"дело {c['дело']} встречается дважды")
        seen_case.add(c["дело"])
        if not c["дело"].isascii():
            bad.append(f"дело {c['дело']}: идентификатор не латиницей — "
                       "«ТР» и «TR» на вид неотличимы, ссылки золотого набора "
                       "перестанут находиться молча")
        for side in c.get("стороны", []):
            if side["инн"] not in known:
                bad.append(f"{c['дело']}: сторона {side['инн']} не в реестре")
        # Пропись сверяется у всех денежных полей, а не у перечисленных
        # поимённо: набор полей зависит от типа договора и будет пополняться.
        for key, m in c.items():
            if isinstance(m, dict) and "прописью" in m:
                if m["прописью"] != rubles_in_words(m["число"]):
                    bad.append(f"{c['дело']}: пропись «{key}» разошлась с числом")
        ds = c.get("допсоглашение_детали")
        if ds:
            if ds["дата"] <= c["дата"]:
                bad.append(f"{c['дело']}: допсоглашение раньше договора")
            if ds["дата"] >= c["дата_окончания"]:
                bad.append(f"{c['дело']}: допсоглашение к уже истёкшему договору")
            for key in ("новая_сумма",):
                if ds[key]["прописью"] != rubles_in_words(ds[key]["число"]):
                    bad.append(f"{c['дело']}: пропись «{key}» разошлась с числом")
            missing = [f for f in ds["меняет"]
                       if f not in c and f != "дата_окончания"]
            if missing:
                bad.append(f"{c['дело']}: допсоглашение меняет поля, "
                           f"которых в договоре нет: {missing}")

    lonely = [inn for inn in known
              if sum(1 for c in data["дела"]
                     for s in c.get("стороны", []) if s["инн"] == inn) == 1]
    if lonely:
        bad.append(f"контрагентов ровно с одним договором: {len(lonely)} — "
                   "фильтр «все договоры с этим контрагентом» на них не проверить")
    return bad


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--orgs", type=int, default=16, help="новых организаций")
    ap.add_argument("--cases", type=int, default=26, help="новых дел")
    ap.add_argument("--ip", type=int, default=4,
                    help="сколько из новых организаций — ИП (ИНН на 12 знаков)")
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true", help="проверить готовый реестр")
    args = ap.parse_args()

    if args.check:
        if not args.out.exists():
            sys.exit(f"нет файла {args.out}")
        data = yaml.safe_load(args.out.read_text(encoding="utf-8"))
        problems = check(data)
        for p in problems:
            print("  ✗", p)
        n_o, n_c = len(data["организации"]), len(data["дела"])
        print(f"\n{args.out.name}: "
              f"{n_o} {_plural(n_o, 'организация', 'организации', 'организаций')}, "
              f"{n_c} {_plural(n_c, 'дело', 'дела', 'дел')} — "
              + ("проверка пройдена" if not problems else
                 f"{len(problems)} {_plural(len(problems), 'замечание', 'замечания', 'замечаний')}"))
        sys.exit(1 if problems else 0)

    data = build(args.seed, args.orgs, args.cases, args.ip)
    args.out.write_text(
        yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=100),
        encoding="utf-8")

    m = data["мета"]
    orgs_w = _plural(m["организаций"], "организация", "организации", "организаций")
    cases_w = _plural(m["дел"], "дело", "дела", "дел")
    try:
        shown = args.out.relative_to(STAND)
    except ValueError:      # --out увели за пределы стенда, печатаем как есть
        shown = args.out
    print(f"{shown}: {m['организаций']} {orgs_w}, "
          f"{m['дел']} {cases_w} (из них {m['из_партии_1']} из партии 1), "
          f"seed {m['seed']}")
    problems = check(data)
    if problems:
        for p in problems:
            print("  ✗", p)
        sys.exit(1)
    print("проверка пройдена: контрольные суммы, пропись, ссылки на стороны")


if __name__ == "__main__":
    main()
