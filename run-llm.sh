#!/bin/bash
# Генеративная модель для локального стенда RAG-lab. llama.cpp, порт 8084.
# Третий процесс: у эмбеддера своя роль, у реранкера своя, совмещать нельзя.
set -euo pipefail

STAND="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
set -a; source "$STAND/.env"; set +a
export LLAMA_CACHE="$STAND/models"

# T-lite-it-2.1 (t-tech): русскоязычная, apache-2.0, GGUF публикует сам вендор.
# Выбор и пять отложенных кандидатов — RAG/research/reference/models.md.
#
# ПЕРВЫЙ ЗАПУСК СКАЧИВАЕТ 6,26 ГБ в models/. Дальше берётся из кэша.
#
# Про память (расчёт, заменить замером `footprint -p PID` после запуска):
#   файл Q6_K                        6,26 ГБ
#   KV-кэш при -c 8192, f16          1,12 ГБ   (36 слоёв × 8 KV-голов ×
#                                               head_dim 128 × 2 × 2 Б =
#                                               144 КиБ на токен)
#   буферы счёта                    ~0,4  ГБ
#   ------------------------------------------
#   итого процесс                   ~7,8  ГБ   (Q8_0 стоил бы ~9,6)
#
# -c 8192: с запасом. Самый длинный чанк партии 1 — 299 токенов, в промпт
#   идут кандидатные фрагменты плюс описание 18 полей. Родительские разделы
#   small-to-big пока не собираются, их длину проверить на партии 2.
#
# --parallel 1: как у эмбеддера — лишние слоты множат KV-кэш без пользы.
#   Извлечение идёт документ за документом, параллелизм здесь не нужен.
#
# Режим рассуждений гасить не нужно: модель его не имеет вовсе
# ("supports only non-thinking mode" в карточке). Это одна из причин выбора.
#
# ВНИМАНИЕ: не вставлять пустых строк между строками с обратным слешем —
# команда молча оборвётся, а лишние аргументы потеряются.
exec llama-server \
  -hf t-tech/T-lite-it-2.1-GGUF:Q6_K \
  --host 127.0.0.1 --port 8084 \
  --api-key "$LLAMA_API_KEY" \
  --cors-origins localhost \
  --parallel 1 \
  -c 8192
