"""Тесты чистых функций реестра партии 2. Скрипт — scripts/make-registry.py.

ПОЧЕМУ ЭТОТ ФАЙЛ ЗАВЕДЁН. Реестр — измерительный прибор для двух этапов
сразу: из него берутся ИНН, на которых проверяется связка «контрагент = ИНН»
(этап 7), и суммы с прописью, на которых проверяется сверка цифр с прописью.
Ошибка в приборе не выглядит ошибкой: договор с 13-значным ИНН читается как
обычный договор, и мы узнаем о дефекте не при генерации, а через неделю,
на разборе метрик.

Первый прогон генератора выдал ровно это — ИНН на 13 знаков вместо 12:
тело считалось как у ИНН юрлица, а контрольных цифр у ИП две, не одна.
Поймала встроенная проверка, но правильное место для такой ловушки — тест.

Запуск:
    uv run pytest -q
"""

import importlib.util
import random
import sys
from pathlib import Path

import pytest

STAND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(STAND / "src"))

from rag_lab.extract import inn_valid  # noqa: E402

# Скрипт лежит в scripts/ и содержит дефис в имени — обычным import не взять.
_spec = importlib.util.spec_from_file_location(
    "make_registry", STAND / "scripts" / "make-registry.py")
mr = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(mr)


# --- Пропись ---------------------------------------------------------------
# Согласование числительных — то место, где ошибка выглядит правдоподобно.
# «одна тысяча» против «один тысяча» человек заметит, а «двадцать одна тысяча»
# против «двадцать один тысяча» — уже не всякий.

@pytest.mark.parametrize("n,words", [
    (0, "ноль"),
    (1, "один"),
    (11, "одиннадцать"),
    (21, "двадцать один"),
    (1_000, "одна тысяча"),          # тысяча женского рода: не «один тысяча»
    (2_000, "две тысячи"),           # и не «два тысячи»
    (11_000, "одиннадцать тысяч"),   # исключение 11–14: не «одиннадцать тысяча»
    (21_000, "двадцать одна тысяча"),
    (112_000, "сто двенадцать тысяч"),
    (1_000_000, "один миллион"),     # миллион мужского рода, в отличие от тысячи
    (2_000_000, "два миллиона"),
    (5_000_000, "пять миллионов"),
    (12_400_000, "двенадцать миллионов четыреста тысяч"),
    (1_234_567, "один миллион двести тридцать четыре тысячи пятьсот шестьдесят семь"),
])
def test_rubles_in_words(n, words):
    assert mr.rubles_in_words(n) == words


def test_money_text_matches_number():
    """В договор идёт строка «6 200 000 (шесть миллионов двести тысяч) рублей».

    Расхождение цифр с прописью мы ловим и показываем человеку. Но проверять
    эту проверку надо на корпусе, где пропись заведомо верна.
    """
    m = mr.money(6_200_000)
    assert m["в_тексте"] == "6 200 000 (шесть миллионов двести тысяч) рублей"
    assert m["прописью"] == mr.rubles_in_words(m["число"])


# --- Контрольные суммы -----------------------------------------------------

def test_generated_inn_passes_pipeline_validator():
    """Генератор и проверка пайплайна должны сходиться на любом seed.

    Проверяется именно `rag_lab.extract.inn_valid` — та же функция, что стоит
    в пайплайне: иначе корпус будет «валиден» по своей собственной мерке.
    """
    rnd = random.Random(1)
    for _ in range(200):
        assert inn_valid(mr._inn10(rnd, "770"))
        assert inn_valid(mr._inn12(rnd, "660"))


def test_inn_lengths():
    """Длина — тот дефект, что был в первом прогоне: 13 знаков вместо 12."""
    rnd = random.Random(2)
    assert len(mr._inn10(rnd, "770")) == 10
    assert len(mr._inn12(rnd, "660")) == 12


def test_ogrn_checksum():
    rnd = random.Random(3)
    for _ in range(100):
        assert mr.ogrn_valid(mr._ogrn(rnd, "77"))
        assert mr.ogrn_valid(mr._ogrn(rnd, "66", ip=True))
    assert not mr.ogrn_valid("1157746123456")   # выдуман для партии 1
    assert not mr.ogrn_valid("123")


def test_ogrn_digits_mean_something():
    """Год регистрации и регион — не случайные цифры.

    Контрольная сумма сходилась и у ОГРН с годом регистрации «97»: формально
    валидно, на вид подделка. Для корпуса, который изображает документы,
    это дефект.
    """
    rnd = random.Random(4)
    for _ in range(50):
        ogrn = mr._ogrn(rnd, "52")
        assert ogrn[0] == "1" and len(ogrn) == 13
        assert 2 <= int(ogrn[1:3]) <= 24        # год регистрации
        assert ogrn[3:5] == "52"                # код региона
        ip = mr._ogrn(rnd, "66", ip=True)
        assert ip[0] == "3" and len(ip) == 15
        assert 2 <= int(ip[1:3]) <= 24 and ip[3:5] == "66"


def test_rates_match_contract_type():
    """Простоя транспорта в аренде не бывает — и это проверяет честный null.

    Поле, которого в договоре нет вовсе, — самая опасная категория:
    модель кладёт в него значение из ближайшего похожего пункта, а оба
    барьера молчат, потому что цитата подлинная.
    """
    data = mr.build(mr.SEED, 16, 26)
    for c in data["дела"]:
        if c["партия"] == 1:
            continue
        if c["тип"] in ("перевозка", "экспедирование"):
            assert "ставка_простоя" in c and "арендная_плата_в_месяц" not in c
        elif c["тип"] == "аренда_ТС":
            assert "арендная_плата_в_месяц" in c and "ставка_простоя" not in c
        else:
            assert "плата_за_паллетоместо_в_сутки" in c and "ставка_простоя" not in c


def test_ip_signs_for_himself():
    """У ИП подписант и есть организация: «ИП Фёдоров» за подписью Беловой — дефект."""
    data = mr.build(mr.SEED, 16, 8)
    for o in data["организации"]:
        if o["партия"] == 2 and o["название_кратко"].startswith("ИП"):
            assert o["название_кратко"] == f"ИП {o['руководитель']['фио']}"


def test_amendment_within_contract_term():
    """Допсоглашение к истёкшему договору — бессмыслица, а выглядит нормально."""
    data = mr.build(mr.SEED, 16, 26)
    for c in data["дела"]:
        ds = c.get("допсоглашение_детали")
        if ds:
            assert c["дата"] < ds["дата"] < c["дата_окончания"]


# --- Реестр целиком --------------------------------------------------------

def test_build_is_deterministic():
    """Один seed — один корпус. Иначе цифры замеров не к чему привязать."""
    assert mr.build(42, 6, 8) == mr.build(42, 6, 8)


def test_build_passes_own_check():
    assert mr.check(mr.build(mr.SEED, 16, 26)) == []


def test_batch_1_inn_left_invalid():
    """Партию 1 не чиним: на ней сделаны все замеры 08–10.08.2026.

    Смешанный корпус проходит обе ветки — валидный ИНН связывается
    с контрагентом, невалидный уходит в очередь ручного сопоставления.
    """
    data = mr.build(mr.SEED, 16, 26)
    first = [o for o in data["организации"] if o["партия"] == 1]
    assert first and all(o["инн_валиден"] is False for o in first)


def test_ip_count_is_requested_not_random():
    """ИП задаётся числом: у него ИНН на 12 знаков — отдельная ветка проверки.

    При вероятности 0,15 на шестнадцати организациях выпадало то одна, то три,
    и ветка могла остаться проверенной на одном примере.
    """
    for n_ip in (0, 1, 4, 7):
        data = mr.build(mr.SEED, 16, 8, n_ip)
        new_ip = [o for o in data["организации"]
                  if o["партия"] == 2 and o["название_кратко"].startswith("ИП")]
        assert len(new_ip) == n_ip
        assert all(len(o["инн"]) == 12 for o in new_ip)


def test_check_catches_broken_words():
    """Проверка обязана ловить правку файла руками, а не только генератор."""
    data = mr.build(mr.SEED, 6, 8)
    case = next(c for c in data["дела"] if "предельная_сумма" in c)
    case["предельная_сумма"]["прописью"] = "сто рублей"
    assert any("пропись" in p for p in mr.check(data))


def test_every_party_appears_in_several_cases():
    """Контрагент в одном договоре не даёт проверить фильтр «все договоры с ним»."""
    data = mr.build(mr.SEED, 16, 26)
    assert mr.check(data) == []
