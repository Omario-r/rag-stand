#!/bin/bash
# Эмбеддер для локального стенда RAG-lab. llama.cpp с Metal, порт 8080.
set -euo pipefail

STAND="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
set -a; source "$STAND/.env"; set +a
export LLAMA_CACHE="$STAND/models"      # модели рядом со стендом, не в ~/Library

# Qwen3-Embedding-0.6B: официальная сборка Qwen, Apache 2.0, размерность 1024.
# Запасной кандидат для сравнения на золотом наборе — ggml-org/bge-m3-Q8_0-GGUF.
#
# Про длину текста и память (замерено 06.08.2026 на этой сборке, b10280):
#   предельную длину ОДНОГО текста задаёт -c, а НЕ --ubatch-size. С дефолтным
#   n_ubatch=512 текст в 30 000 токенов обрабатывается нормально. Старое правило
#   «последовательность должна влезть в один физический батч» на этой сборке
#   не действует — проверено, см. RAG/03-embeddings.md.
#
#   -c 2048 →  947 МБ      -c 8192 → 1619 МБ
#   -c 4096 → 1171 МБ      -c 16384 → 2515 МБ
#
#   Взято 8192: покрывает родительские разделы для small-to-big с запасом,
#   лишние ~670 МБ против 2048 на 24 ГБ несущественны.
#
# --parallel 1: дефолтные 4 слота множат KV-кэш вчетверо без пользы для
#   пакетной векторизации (именно это давало 4,2 ГБ на первом замере).
#
# ВНИМАНИЕ: не вставлять пустых строк между строками с обратным слешем —
# команда молча оборвётся, а лишние аргументы потеряются. Это уже случалось.
exec llama-server \
  -hf Qwen/Qwen3-Embedding-0.6B-GGUF:Q8_0 \
  --embeddings \
  --host 127.0.0.1 --port 8080 \
  --api-key "$LLAMA_API_KEY" \
  --cors-origins localhost \
  --parallel 1 \
  -c 8192
